import { test, expect } from '@playwright/test';
test('real EPUB: rendering, selection, highlights, search, anchors and isolation', async ({ page }) => {
  const errors: string[] = [];
  const remote: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', req => { if (req.url().includes('example.invalid')) remote.push(req.url()); });
  await page.goto('/');
  await expect(page.locator('body')).toHaveAttribute('data-ready', 'true');
  const frame = page.frameLocator('iframe').first();
  await expect(frame.locator('h1')).toHaveText('A place to begin');
  await expect(frame.locator('#lead')).toHaveCSS('font-family', 'Georgia, serif');
  const sandbox = await page.locator('iframe').first().getAttribute('sandbox');
  expect(sandbox).not.toContain('allow-scripts');
  expect(await page.evaluate(() => (window as any).BOOK_SCRIPT_RAN)).toBeUndefined();
  expect(remote).toEqual([]);
  await frame.locator('#lead').evaluate(el => {
    const range = el.ownerDocument.createRange(); range.setStart(el.firstChild!, 0); range.setEnd(el.firstChild!, el.textContent!.length);
    const selection = el.ownerDocument.defaultView!.getSelection()!;
    selection.removeAllRanges(); selection.addRange(range);
    el.ownerDocument.dispatchEvent(new Event('selectionchange'));
  });
  await expect.poll(() => page.evaluate(() => (window as any).testReader.state.selected?.text)).toBe('Every idea begins with a small act of attention.');
  const selected = await page.evaluate(() => (window as any).testReader.state.selected);
  const annotation = { ...selected, id: 'a', comment: '', color: 'yellow', kind: 'highlight', created: '2026-10-12' };
  await page.evaluate(a => (window as any).testReader.highlight(a), annotation);
  await expect(page.locator('svg .ebook-highlight')).toHaveCount(1);
  expect(await page.evaluate(cfi => (window as any).testReader.textAt(cfi), selected.cfi)).toBe(selected.text);
  const hits = await page.evaluate(() => (window as any).testReader.search('living conversation'));
  expect(hits).toHaveLength(1);
  await page.evaluate(cfi => (window as any).testReader.go(cfi), hits[0].cfi);
  await expect(frame.locator('h1')).toHaveText('Following a thought');
  await page.evaluate(cfi => (window as any).testReader.open(cfi), selected.cfi);
  await expect(frame.locator('#lead')).toHaveText(selected.text);
  await page.evaluate(a => (window as any).testReader.highlight(a), annotation);
  await expect(page.locator('svg .ebook-highlight')).toHaveCount(1);
  await page.evaluate(a => (window as any).testReader.remove(a), annotation);
  await expect(page.locator('svg .ebook-highlight')).toHaveCount(0);
  await page.evaluate(() => (window as any).testReader.style());
  await expect(frame.locator('body')).toHaveCSS('background-color', 'rgb(32, 33, 36)');
  await page.screenshot({ path: 'test-results/reader.png' });
  expect(errors).toEqual([]);
});
test('malformed archives report an error rather than leaving the reader loading', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('body')).toHaveAttribute('data-ready', 'true');
  const message = await page.evaluate(() => (window as any).testReader.malformed());
  expect(message).toContain('zip');
  expect(message).not.toContain('unexpected success');
});
